/// <summary>
/// A resolved icon: the avares:// path for use as an SVG image source and the
/// localized accessible label for <c>AutomationProperties.Name</c>.
/// </summary>
/// <param name="AvaresPath">The <c>avares://OgmaLibrary.App/Assets/icons/…</c> path.</param>
/// <param name="AccessibleLabel">The localized string for the icon's accessible label.</param>
