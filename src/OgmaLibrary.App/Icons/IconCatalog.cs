    /// <summary>
    /// Returns the full <c>avares://</c> path for the given icon key, or <c>null</c> if the
    /// key is not registered.
    /// </summary>
    /// <param name="key">The icon key (e.g. <c>"ic_app_logo"</c>).</param>
    /// <returns>The <c>avares://OgmaLibrary.App/Assets/icons/…</c> URI string.</returns>
    public static string? GetAvaresPath(string key)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(key);
        return AssetPaths.TryGetValue(key, out string? rel) ? AssemblyPrefix + rel : null;
    }

    /// <summary>
    /// Resolves an icon to its avares:// path and localized accessible label.
    /// Returns <c>null</c> if the key is not registered.
    /// </summary>
    /// <param name="key">The icon key (e.g. <c>"ic_settings"</c>).</param>
    /// <param name="localization">The active localization service.</param>
    /// <returns>
    /// An <see cref="IconEntry"/> with the asset path and accessible label, or <c>null</c>.
    /// </returns>
    public static IconEntry? Resolve(string key, ILocalizationService localization)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(key);
        ArgumentNullException.ThrowIfNull(localization);

        if (!AssetPaths.TryGetValue(key, out string? rel))
        {
            return null;
        }

        string path = AssemblyPrefix + rel;
        string labelKey = $"Icon.{key}.Label";
        string label = localization[labelKey];
        return new IconEntry(path, label);
    }

    /// <summary>
    /// Returns all registered icon keys.
    /// </summary>
    public static IEnumerable<string> AllKeys => AssetPaths.Keys;
}
